func findSpec(class, spec string) (Class, Spec, bool) {
	for _, c := range classes {
		if c.Token == class {
			for _, s := range c.Specs {
				if s.Token == spec {
					return c, s, true
				}
			}
		}
	}
	return Class{}, Spec{}, false
}

var aplGenMu sync.Mutex

// defaultAPL returns the default action priority list SimulationCraft builds
// for a class/spec. It is generated by the installed simc build itself (so it
// always matches the engine) and cached per simc version.
func (a *App) defaultAPL(class, spec string, refresh bool) (string, error) {
	if _, _, ok := findSpec(class, spec); !ok {
		return "", errors.New("unknown class/spec")
	}
	if a.simcPath() == "" {
		return "", errors.New("SimulationCraft is not installed yet. Open Settings and click Install")
	}
	dir := a.path("apl", "default", a.simcVersionKey())
	cache := filepath.Join(dir, class+"_"+spec+".simc")
	if !refresh {
		if b, err := os.ReadFile(cache); err == nil {
			return string(b), nil
		}
	}
	aplGenMu.Lock()
	defer aplGenMu.Unlock()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	work, err := os.MkdirTemp(a.path("tmp"), "apl-")
	if err != nil {
		return "", err
	}
	defer os.RemoveAll(work)
	input := fmt.Sprintf("%s=\"Default_%s\"\nspec=%s\nsave=profile.simc\niterations=1\nmax_time=20\nthreads=1\nreport_details=0\n",
		class, spec, spec)
	if err := os.WriteFile(filepath.Join(work, "input.simc"), []byte(input), 0o644); err != nil {
		return "", err
	}
	j := &job{State: jobRunning}
	j.ctx, j.cancel = contextWithTimeout(2 * time.Minute)
	defer j.cancel()
	runErr := a.runSimc(j, work, "input.simc")
	b, err := os.ReadFile(filepath.Join(work, "profile.simc"))
	if err != nil {
		msg := "simc did not produce a profile"
		if runErr != nil {
			msg = runErr.Error()
		}
		return "", fmt.Errorf("%s:\n%s", msg, strings.Join(tail(j.Lines, 15), "\n"))
	}
	apl := extractActions(string(b))
	if apl == "" {
		return "", errors.New("simc has no default action list for this spec")
	}
	_ = writeFileAtomic(cache, []byte(apl))
	return apl, nil
}

func tail(lines []string, n int) []string {
	if len(lines) > n {
		return lines[len(lines)-n:]
	}
	return lines
}

// extractActions keeps the actions block (and its comments) of a saved profile.
func extractActions(profile string) string {
	lines := strings.Split(strings.ReplaceAll(profile, "\r\n", "\n"), "\n")
	first, last := -1, -1
	for i, l := range lines {
		if strings.HasPrefix(strings.TrimSpace(l), "actions") {
			if first < 0 {
				first = i
			}
			last = i
		}
	}
	if first < 0 {
		return ""
	}
	// Pull in the comment block right above the first action line.
	for first > 0 && strings.HasPrefix(strings.TrimSpace(lines[first-1]), "#") {
		first--
	}
	return strings.TrimSpace(strings.Join(lines[first:last+1], "\n")) + "\n"
}

// CustomAPL is a user-edited action list stored in apl/custom.
type CustomAPL struct {
	ID      string    `json:"id"`
	Name    string    `json:"name"`
	Class   string    `json:"class"`
	Spec    string    `json:"spec"`
	Content string    `json:"content,omitempty"`
	Updated time.Time `json:"updated"`
}

func (a *App) listCustomAPLs() []CustomAPL {
	out := []CustomAPL{}
	files, _ := filepath.Glob(a.path("apl", "custom", "*.json"))
	for _, f := range files {
		var c CustomAPL
		if b, err := os.ReadFile(f); err == nil && json.Unmarshal(b, &c) == nil {
			c.Content = ""
			out = append(out, c)
		}
	}
	sort.Slice(out, func(i, k int) bool { return out[i].Updated.After(out[k].Updated) })
	return out
}

func (a *App) getCustomAPL(id string) (CustomAPL, error) {
	var c CustomAPL
	b, err := os.ReadFile(a.path("apl", "custom", sanitizeName(id)+".json"))
	if err != nil {
		return c, errors.New("custom APL not found")
	}
	err = json.Unmarshal(b, &c)
	return c, err
}

func (a *App) saveCustomAPL(c CustomAPL) (CustomAPL, error) {
	if strings.TrimSpace(c.Name) == "" {
		return c, errors.New("give the APL a name")
	}
	if strings.TrimSpace(c.Content) == "" {
		return c, errors.New("the APL is empty")
	}
	if c.ID == "" {
		c.ID = newID()
	}
	c.ID = sanitizeName(c.ID)
	c.Updated = time.Now()
	b, _ := json.MarshalIndent(c, "", "  ")
	return c, writeFileAtomic(a.path("apl", "custom", c.ID+".json"), b)
}

func (a *App) deleteCustomAPL(id string) error {
	return os.Remove(a.path("apl", "custom", sanitizeName(id)+".json"))
}

// SampleProfile is a character profile shipped in the simc profiles folder.
type SampleProfile struct {
	Tier string `json:"tier"`
	Name string `json:"name"`
	Path string `json:"path"`
}

func (a *App) sampleProfiles() []SampleProfile {
	root := a.simcRoot()
	if root == "" {
		return []SampleProfile{}
	}
	out := []SampleProfile{}
	base := filepath.Join(root, "profiles")
	_ = filepath.Walk(base, func(p string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() || !strings.HasSuffix(info.Name(), ".simc") {
			return nil
		}
		rel, _ := filepath.Rel(base, p)
		tier := filepath.Dir(rel)
		if tier == "." {
			tier = "Other"
		}
		name := strings.TrimSuffix(info.Name(), ".simc")
		out = append(out, SampleProfile{Tier: filepath.ToSlash(tier), Name: strings.ReplaceAll(name, "_", " "), Path: filepath.ToSlash(rel)})
		return nil
	})
	sort.Slice(out, func(i, k int) bool {
		if out[i].Tier != out[k].Tier {
			return out[i].Tier > out[k].Tier // newest tier names sort last alphabetically
		}
		return out[i].Name < out[k].Name
	})
	return out
}

func (a *App) readSampleProfile(rel string) (string, error) {
	root := a.simcRoot()
	if root == "" {
		return "", errors.New("SimulationCraft is not installed")
	}
	base := filepath.Join(root, "profiles")
	p, err := safeJoin(base, rel)
	if err != nil {
		return "", err
	}
	b, err := os.ReadFile(p)
	return string(b), err
}
