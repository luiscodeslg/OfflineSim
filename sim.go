// SimRequest is what the UI posts to start a simulation.
type SimRequest struct {
	Type        string  `json:"type"` // quick, stats, topgear, apl, advanced
	Title       string  `json:"title"`
	Profile     string  `json:"profile"`
	FightStyle  string  `json:"fightStyle"`
	MaxTime     int     `json:"maxTime"`
	Targets     int     `json:"targets"`
	Iterations  int     `json:"iterations"` // 0 = use target error
	TargetError float64 `json:"targetError"`
	Extra       string  `json:"extra"` // raw simc lines appended at the end

	// APL selection. Empty = engine default.
	CustomAPL string   `json:"customApl"`
	CompareTo []string `json:"compareTo"` // apl type: extra custom APL ids ("default" = engine default)

	// Top Gear: indexes into ProfileInfo.Items that may be tried.
	Items     []int `json:"items"`
	MaxCombos int   `json:"maxCombos"`
}

type comboInfo struct {
	Name    string   `json:"name"`
	Changes []string `json:"changes"`
}

var fightStyles = []string{"Patchwerk", "CastingPatchwerk", "LightMovement", "HeavyMovement", "HecticAddCleave", "CleaveAdd", "DungeonSlice", "DungeonRoute"}

func validFightStyle(s string) bool {
	for _, f := range fightStyles {
		if f == s {
			return true
		}
	}
	return false
}

func simTypeName(t string) string {
	switch t {
	case "stats":
		return "Stat Weights"
	case "topgear":
		return "Top Gear"
	case "apl":
		return "APL Compare"
	case "advanced":
		return "Advanced"
	}
	return "Quick Sim"
}

// buildInput turns a request into a simc input file. It returns the input and
// the Top Gear combo descriptions (if any).
func (a *App) buildInput(req SimRequest) (string, []comboInfo, error) {
	var b strings.Builder
	line := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	profile := strings.ReplaceAll(req.Profile, "\r\n", "\n")
	if strings.TrimSpace(profile) == "" {
		return "", nil, errors.New("paste a /simc addon string or a SimulationCraft profile first")
	}
	line("# Generated by %s %s on %s", appName, appVersion, time.Now().Format(time.RFC1123))
	line("json2=result.json")
	line("html=report.html")
	if req.Type == "advanced" {
		if !strings.Contains(profile, "threads=") {
			line("threads=%d", a.threads())
		}
		line("")
		b.WriteString(profile)
		line("")
		return b.String(), nil, nil
	}

	info := parseProfile(profile)
	if info.Class == "" {
		return "", nil, errors.New("couldn't find a character in the input. Use the /simc addon output, which starts with a line like  mage=\"Name\"")
	}
	line("threads=%d", a.threads())
	if req.Iterations > 0 {
		line("iterations=%d", req.Iterations)
		line("target_error=0")
	} else {
		te := req.TargetError
		if te <= 0 {
			te = 0.1
		}
		line("target_error=%g", te)
	}
	fs := req.FightStyle
	if !validFightStyle(fs) {
		fs = "Patchwerk"
	}
	line("fight_style=%s", fs)
	if req.MaxTime > 0 {
		line("max_time=%d", req.MaxTime)
	}
	if req.Targets > 1 {
		line("desired_targets=%d", req.Targets)
	}
	if req.Type == "stats" {
		ps := primaryStat(info.Class, info.Spec)
		line("calculate_scale_factors=1")
		line("scale_only=%s,crit_rating,haste_rating,mastery_rating,versatility_rating", ps)
	}
	if req.Type == "apl" {
		// Every actor is simulated on its own so they can't buff each other.
		line("single_actor_batch=1")
	}
	line("")
	b.WriteString(strings.TrimSpace(profile))
	line("")

	if req.CustomAPL != "" && req.CustomAPL != "default" {
		c, err := a.getCustomAPL(req.CustomAPL)
		if err != nil {
			return "", nil, err
		}
		line("")
		line("# --- Custom APL: %s ---", c.Name)
		b.WriteString(normalizeAPL(c.Content))
	}

	var combos []comboInfo
	switch req.Type {
	case "apl":
		if len(req.CompareTo) == 0 {
			return "", nil, errors.New("pick at least one APL to compare against")
		}
		base := info.Name
		if base == "" {
			base = "Player"
		}
		for i, id := range req.CompareTo {
			var content, label string
			if id == "default" {
				apl, err := a.defaultAPL(info.Class, info.Spec, false)
				if err != nil {
					return "", nil, fmt.Errorf("default APL: %w", err)
				}
				content, label = apl, "Default APL"
			} else {
				c, err := a.getCustomAPL(id)
				if err != nil {
					return "", nil, err
				}
				content, label = c.Content, c.Name
			}
			name := fmt.Sprintf("%s_%d_%s", sanitizeName(base), i+2, sanitizeName(label))
			line("")
			line("# --- Compare: %s ---", label)
			line("copy=%s,%s", name, quoteIfNeeded(base))
			b.WriteString(normalizeAPL(content))
		}
	case "topgear":
		var err error
		combos, err = topGearCombos(info, req.Items, req.MaxCombos)
		if err != nil {
			return "", nil, err
		}
		line("")
		line("# --- Top Gear: %d combinations ---", len(combos))
		for _, c := range combos {
			for _, ch := range c.Changes {
				line("profileset.\"%s\"+=%s", c.Name, ch)
			}
		}
	}
	if strings.TrimSpace(req.Extra) != "" {
		line("")
		line("# --- Extra options ---")
		b.WriteString(strings.TrimSpace(req.Extra))
		line("")
	}
	return b.String(), combos, nil
}

func quoteIfNeeded(s string) string {
	if strings.ContainsAny(s, " \t") {
		return `"` + s + `"`
	}
	return s
}

// normalizeAPL makes sure a pasted action list replaces the default one: the
// first line of each action list must be an assignment (=), not an append (+=).
func normalizeAPL(apl string) string {
	seen := map[string]bool{}
	var out []string
	for _, raw := range strings.Split(strings.ReplaceAll(apl, "\r\n", "\n"), "\n") {
		l := strings.TrimSpace(raw)
		if strings.HasPrefix(l, "actions") {
			if i := strings.Index(l, "+="); i > 0 && !strings.Contains(l[:i], "=") {
				list := l[:i]
				if !seen[list] {
					rest := strings.TrimPrefix(l[i+2:], "/")
					l = list + "=" + rest
				}
				seen[list] = true
			} else if i := strings.Index(l, "="); i > 0 {
				seen[l[:i]] = true
			}
		}
		out = append(out, l)
	}
	return strings.TrimSpace(strings.Join(out, "\n")) + "\n"
}

// topGearCombos builds every gear set from the selected items, with rings and
// trinkets treated as unordered pairs.
func topGearCombos(info ProfileInfo, selected []int, maxCombos int) ([]comboInfo, error) {
	if maxCombos <= 0 {
		maxCombos = 1500
	}
	sel := map[int]bool{}
	for _, i := range selected {
		sel[i] = true
	}
	type option struct {
		slots  []string
		values []string
		labels []string
	}
	groups := map[string][]GearItem{}
	var order []string
	equipped := map[string]GearItem{}
	for _, it := range info.Items {
		if it.Equipped {
			equipped[it.Slot] = it
		}
		if !it.Equipped && !sel[it.Index] {
			continue
		}
		if _, ok := groups[it.Group]; !ok {
			order = append(order, it.Group)
		}
		// Skip exact duplicates (same item string) within a group.
		dup := false
		for _, o := range groups[it.Group] {
			if o.Value == it.Value && o.Equipped == it.Equipped {
				dup = true
			}
		}
		if !dup {
			groups[it.Group] = append(groups[it.Group], it)
		}
	}

	var axes [][]option
	for _, g := range order {
		items := groups[g]
		var opts []option
		if g == "finger" || g == "trinket" {
			s1, s2 := g+"1", g+"2"
			eq1, eq2 := equipped[s1], equipped[s2]
			// Equipped pair first, unchanged.
			opts = append(opts, option{})
			for i := 0; i < len(items); i++ {
				for k := i + 1; k < len(items); k++ {
					x, y := items[i], items[k]
					if x.Value == y.Value || (itemID(x.Value) != "" && itemID(x.Value) == itemID(y.Value)) {
						continue // can't wear the same item twice
					}
					if (x.Value == eq1.Value && y.Value == eq2.Value) || (x.Value == eq2.Value && y.Value == eq1.Value) {
						continue
					}
					// Keep an equipped item in its current slot.
					if y.Value == eq1.Value || x.Value == eq2.Value {
						x, y = y, x
					}
					opts = append(opts, option{slots: []string{s1, s2}, values: []string{x.Value, y.Value}, labels: []string{x.Label, y.Label}})
				}
			}
		} else {
			opts = append(opts, option{})
			eq := equipped[g]
			for _, it := range items {
				if it.Equipped || it.Value == eq.Value {
					continue
				}
				opts = append(opts, option{slots: []string{g}, values: []string{it.Value}, labels: []string{it.Label}})
			}
		}
		if len(opts) > 1 {
			axes = append(axes, opts)
		}
	}
	total := 1
	for _, ax := range axes {
		total *= len(ax)
		if total > 1_000_000 {
			break
		}
	}
	if total <= 1 {
		return nil, errors.New("select at least one item from your bags (or vault) to compare against what you have equipped")
	}
	if total-1 > maxCombos {
		return nil, fmt.Errorf("that is %d combinations, over the limit of %d. Deselect some items", total-1, maxCombos)
	}
	var combos []comboInfo
	idx := make([]int, len(axes))
	for {
		// Advance the odometer; the all-zero state is the equipped baseline.
		k := 0
		for k < len(axes) {
			idx[k]++
			if idx[k] < len(axes[k]) {
				break
			}
			idx[k] = 0
			k++
		}
		if k == len(axes) {
			break
		}
		var c comboInfo
		c.Name = fmt.Sprintf("Combo %d", len(combos)+1)
		for ai, oi := range idx {
			o := axes[ai][oi]
			for si := range o.slots {
				c.Changes = append(c.Changes, o.slots[si]+"="+o.values[si])
			}
		}
		combos = append(combos, c)
	}
	return combos, nil
}

// labelChanges returns human readable item names for a combo.
func labelChanges(info ProfileInfo, changes []string) []string {
	equipped := map[string]string{}
	for _, it := range info.Items {
		if it.Equipped {
			equipped[it.Slot] = it.Value
		}
	}
	var out []string
	for _, ch := range changes {
		slot, val, _ := strings.Cut(ch, "=")
		if equipped[slot] == val {
			continue // the other half of a ring/trinket pair that didn't change
		}
		label := val
		for _, it := range info.Items {
			if it.Value == val {
				label = it.Label
				break
			}
		}
		out = append(out, slot+": "+label)
	}
	return out
}

func (a *App) startSim(req SimRequest) (*job, error) {
	if a.simcPath() == "" {
		return nil, errors.New("SimulationCraft is not installed yet. Open Settings and click Install")
	}
	if j := a.jobs.running("sim"); j != nil {
		return nil, errors.New("a simulation is already running")
	}
	input, combos, err := a.buildInput(req)
	if err != nil {
		return nil, err
	}
	info := parseProfile(req.Profile)
	if req.Type != "advanced" {
		if v, err := a.simcVersion(); err == nil {
			if msg := compatProblem(engineInfo(v), info, req.Profile); msg != "" {
				return nil, errors.New(msg)
			}
		}
	}
	title := req.Title
	if title == "" {
		title = simTypeName(req.Type)
		if info.Name != "" {
			title += " - " + info.Name
		}
	}
	return a.jobs.start("sim", title, func(j *job) (string, error) {
		id := j.ID
		dir := a.path("results", id)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return "", err
		}
		_ = os.WriteFile(filepath.Join(dir, "input.simc"), []byte(input), 0o644)
		rb, _ := json.MarshalIndent(req, "", "  ")
		_ = os.WriteFile(filepath.Join(dir, "request.json"), rb, 0o644)
		j.setProgress(-1, "Starting SimulationCraft")
		start := time.Now()
		if err := a.runSimc(j, dir, "input.simc"); err != nil {
			_ = os.WriteFile(filepath.Join(dir, "log.txt"), []byte(strings.Join(j.Lines, "\n")), 0o644)
			if j.ctx.Err() != nil {
				os.RemoveAll(dir)
			}
			return "", err
		}
		_ = os.WriteFile(filepath.Join(dir, "log.txt"), []byte(strings.Join(j.Lines, "\n")), 0o644)
		raw, err := os.ReadFile(filepath.Join(dir, "result.json"))
		if err != nil {
			return "", errors.New("simc finished but wrote no results; see the log")
		}
		sum, err := summarize(raw)
		if err != nil {
			return "", fmt.Errorf("reading simc results: %w", err)
		}
		sum.ID, sum.Title, sum.Type = id, title, req.Type
		sum.Created = time.Now()
		sum.WallSeconds = time.Since(start).Seconds()
		if len(combos) > 0 {
			labels := map[string][]string{}
			for _, c := range combos {
				labels[c.Name] = labelChanges(info, c.Changes)
			}
			for i := range sum.Profilesets {
				sum.Profilesets[i].Changes = labels[sum.Profilesets[i].Name]
			}
		}
		sb, _ := json.MarshalIndent(sum, "", " ")
		if err := os.WriteFile(filepath.Join(dir, "summary.json"), sb, 0o644); err != nil {
			return "", err
		}
		return id, nil
	}), nil
}

// HistoryEntry is a row in the results list.
type HistoryEntry struct {
	ID      string    `json:"id"`
	Title   string    `json:"title"`
	Type    string    `json:"type"`
	Created time.Time `json:"created"`
	Spec    string    `json:"spec"`
	DPS     float64   `json:"dps"`
	Fight   string    `json:"fight"`
}

func (a *App) history() []HistoryEntry {
	out := []HistoryEntry{}
	files, _ := filepath.Glob(a.path("results", "*", "summary.json"))
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			continue
		}
		var s Summary
		if json.Unmarshal(b, &s) != nil {
			continue
		}
		e := HistoryEntry{ID: s.ID, Title: s.Title, Type: s.Type, Created: s.Created, Fight: s.FightStyle}
		if len(s.Actors) > 0 {
			e.Spec = s.Actors[0].Spec
			e.DPS = s.Actors[0].DPS.Mean
		}
		out = append(out, e)
	}
	sort.Slice(out, func(i, k int) bool { return out[i].Created.After(out[k].Created) })
	return out
}

var itemIDRe = regexp.MustCompile(`(?:^|,)id=(\d+)`)

func itemID(value string) string {
	if m := itemIDRe.FindStringSubmatch(value); m != nil {
		return m[1]
	}
	return ""
}
